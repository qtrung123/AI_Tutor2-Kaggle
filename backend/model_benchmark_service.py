"""Admin-only Quiz model benchmark (V1): Qwen 2.5 7B vs Gemma 3 12B on identical inputs.

Runs the existing live Quiz pipeline (backend.quiz_service.generate_quiz) sequentially, once per
(model, document, run number), always with regenerate=True so no run can be a cache hit. It never
changes prompts, models, retries or validation, and it never falls back to another model: every
run must be generated by exactly the model it was asked for, or it is recorded as a failure.

Identical inputs: each document's content hash and flashcard snapshot (the flashcards the live
pipeline reads as fill-blank hints) are captured once when the benchmark starts and re-checked
before and after every run; a mismatch fails that run instead of silently comparing different
inputs. Difficulty, question count and scope are shared by every run.

Fair timing: before a model's measured runs, a warm-up phase pulls it if needed
(prepare_generation_model -> model_prepare_ms) and loads it into memory with the same num_ctx the
Quiz calls use (warm_generation_model -> warm_ms). Both are stored per model as the cold-start
metric and are never part of a measured run: a run's latency is the diagnostics total_ms of
generate_quiz alone. Each run also keeps Ollama's in-run load time (ollama_load_ms), so a reload
during a run would stay visible instead of silently inflating latency.

Isolation: every benchmark quiz is saved with a benchmark_id (quiz_store.saving_benchmark_quizzes),
which keeps it out of the Quiz Library, quiz reuse, Study Planner and history while it stays
loadable by its quiz_id, recorded on the run.

Every finished run (success or failure) is appended to the stored state and the per-model
aggregates are recomputed, so the admin page shows progress and survives a reload. A failed run is
recorded and the remaining runs continue. Unavailable metrics are stored as null.
"""

from __future__ import annotations

import hashlib
import json
import math
import threading
from datetime import datetime, timezone
from uuid import uuid4

from backend import quiz_diagnostics
from backend.flashcard_service import FLASHCARD_VERSION
from backend.flashcard_store import get_latest_flashcard_set_info, list_flashcards
from backend.model_benchmark_store import load_benchmark_state, save_benchmark_state
from backend.model_registry import (
    describe_generation_model, prepare_generation_model, resolve_generation_model, warm_generation_model,
)
from backend.quiz_service import (
    QUIZ_DIFFICULTIES, QUIZ_GENERATION_KEEP_ALIVE, QUIZ_V2_ALLOWED_QUESTION_COUNTS, _document_lookup, generate_quiz,
)
from backend.quiz_store import saving_benchmark_quizzes
from backend.quiz_units import QUIZ_ENGINE_VERSION, QUIZ_NUM_CTX, QUIZ_PROMPT_VERSION, flashcard_hint_terms

BENCHMARK_MODELS = (
    {"model_id": "qwen-2.5-7b", "label": "Qwen 2.5 7B"},
    {"model_id": "gemma3-12b", "label": "Gemma 3 12B"},
)
BENCHMARK_SCOPE = "document"
DEFAULT_RUNS = 3
MAX_RUNS = 10
MAX_DOCUMENTS = 10


class BenchmarkAlreadyRunning(RuntimeError):
    pass


class BenchmarkInputChanged(RuntimeError):
    """The document or its flashcard snapshot changed after the benchmark started."""


class BenchmarkModelMismatch(RuntimeError):
    """The quiz was not generated by the requested model (never silently accepted)."""


class BenchmarkCacheHit(RuntimeError):
    """The run was served from the quiz cache instead of being generated."""


class BenchmarkWarmupFailed(RuntimeError):
    """The model could not be prepared/loaded, so its runs were not measured."""


def _now() -> str:
    return datetime.now(timezone.utc).isoformat()


def _sha256(value) -> str:
    return hashlib.sha256(json.dumps(value, ensure_ascii=False, sort_keys=True).encode("utf-8")).hexdigest()


# ---------------------------------------------------------------------------
# Input snapshots
# ---------------------------------------------------------------------------

def flashcard_snapshot(document: dict, owner_id: str) -> dict:
    """The flashcards the live pipeline reads for this document (same lookup as
    quiz_service._flashcard_coverage_hints), reduced to a count and a content hash."""
    info = get_latest_flashcard_set_info(
        owner_id, document["id"], str(document.get("hash") or ""), int(document.get("topic_schema_version") or 0),
        FLASHCARD_VERSION,
    )
    cards = list_flashcards(owner_id, document["id"], info["set_id"]) if info else []
    hint_terms = flashcard_hint_terms(cards)
    content = [[str(card.get("front") or ""), str(card.get("back") or "")] for card in cards]
    return {
        "set_id": info["set_id"] if info else None,
        "flashcard_count": len(cards),
        "flashcard_hash": _sha256({"set_id": info["set_id"] if info else None, "cards": content}),
        "hint_term_count": len(hint_terms),
        "hint_terms_hash": _sha256(hint_terms),
    }


def _document_inputs(document_id: str, owner_id: str) -> dict:
    document = _document_lookup(owner_id).get(document_id)
    if document is None:
        raise BenchmarkInputChanged(f"document {document_id} is no longer indexed.")
    return {
        "document_id": document_id,
        "title": document.get("title") or document_id,
        "document_hash": str(document.get("hash") or "") or None,
        "topic_schema_version": int(document.get("topic_schema_version") or 0),
        **flashcard_snapshot(document, owner_id),
    }


def _assert_inputs_unchanged(expected: dict, owner_id: str, when: str) -> None:
    current = _document_inputs(expected["document_id"], owner_id)
    for key in ("document_hash", "topic_schema_version", "flashcard_hash"):
        if current[key] != expected[key]:
            raise BenchmarkInputChanged(f"{key} changed {when} this run ({expected[key]} -> {current[key]}).")


# ---------------------------------------------------------------------------
# Warm-up (cold start), measured separately from every run
# ---------------------------------------------------------------------------

def warm_up_model(model: dict) -> dict:
    """Pull (if needed) and load one model before its measured runs. Never raises."""
    record = {
        "model_id": model["model_id"],
        "model_ref": model.get("model_ref"),
        "model_prepare_ms": None,
        "pulled": None,
        "warm_ms": None,
        "ollama_load_ms": None,
        "cold_start_ms": None,
        "num_ctx": QUIZ_NUM_CTX,
        "success": False,
        "error": None,
        "started_at": _now(),
        "finished_at": None,
    }
    try:
        prepared = prepare_generation_model(model["model_id"])
        record["model_prepare_ms"] = prepared.get("model_prepare_ms")
        record["pulled"] = bool(prepared.get("prepared"))
        warmed = warm_generation_model(model["model_id"], QUIZ_NUM_CTX, QUIZ_GENERATION_KEEP_ALIVE)
        record["warm_ms"] = warmed.get("warm_ms")
        record["ollama_load_ms"] = warmed.get("ollama_load_ms")
        record["cold_start_ms"] = _sum_or_none([record["model_prepare_ms"], record["warm_ms"]])
        record["success"] = True
    except Exception as error:
        record["error"] = {"type": type(error).__name__, "message": str(error)[:500]}
    record["finished_at"] = _now()
    return record


# ---------------------------------------------------------------------------
# One run
# ---------------------------------------------------------------------------

def _sum_or_none(values) -> int | None:
    known = [value for value in values if isinstance(value, (int, float))]
    return sum(known) if known else None


def _tokens_per_second(calls: list[dict]) -> float | None:
    """Generated tokens / token-generation seconds over the calls where Ollama reported both."""
    tokens = seconds = 0.0
    for call in calls:
        generated, rate = call.get("generated_tokens"), call.get("tokens_per_s")
        if isinstance(generated, (int, float)) and isinstance(rate, (int, float)) and generated and rate:
            tokens += generated
            seconds += generated / rate
    return round(tokens / seconds, 1) if seconds else None


def _empty_run(model: dict, model_ref: str | None, inputs: dict, config: dict, run_number: int) -> dict:
    described = describe_generation_model(model_ref) if model_ref else {}
    return {
        "run_id": str(uuid4()),
        "model_id": model["model_id"],
        "model_label": model["label"],
        "model_ref": model_ref,
        "quantization": described.get("quantization"),
        "document_id": inputs["document_id"],
        "document_title": inputs["title"],
        "document_hash": inputs["document_hash"],
        "flashcard_set_id": inputs["set_id"],
        "flashcard_count": inputs["flashcard_count"],
        "flashcard_hash": inputs["flashcard_hash"],
        "difficulty": config["difficulty"],
        "question_count": config["question_count"],
        "assessment_scope": BENCHMARK_SCOPE,
        "run_number": run_number,
        "quiz_engine_version": QUIZ_ENGINE_VERSION,
        "quiz_prompt_version": QUIZ_PROMPT_VERSION,
        "generation_config": None,
        "retrieval_ms": None,
        "generation_ms": None,
        "total_ms": None,
        "ollama_load_ms": None,
        "llm_calls": None,
        "retries": None,
        "cache_hit": None,
        "prompt_tokens": None,
        "generated_tokens": None,
        "tokens_per_second": None,
        "requested_count": config["question_count"],
        "final_count": None,
        "validated_count": None,
        "rejected_count": None,
        "grounding_rejections": None,
        "rejection_reasons": None,
        "question_type_distribution": None,
        "quiz_id": None,
        "benchmark_id": None,
        "generated_by": None,
        "success": False,
        "error": None,
        "started_at": _now(),
        "finished_at": None,
    }


def _apply_summary(record: dict, summary: dict) -> None:
    """Fill timings/calls/retries from the run's quiz_diagnostics summary (present on failure too)."""
    if not summary:
        return
    for key in ("retrieval_ms", "generation_ms", "total_ms", "llm_calls"):
        if summary.get(key) is not None:
            record[key] = summary[key]
    if summary.get("retry_count") is not None:
        record["retries"] = summary["retry_count"]
    record["cache_hit"] = summary.get("cache_hit")


def _apply_quiz(record: dict, quiz: dict) -> None:
    plan = quiz.get("assessment_plan") or {}
    calls = [call for call in (plan.get("calls") or []) if isinstance(call, dict)]
    results = plan.get("validation_results") or {}
    timings = plan.get("timings_ms") or {}
    record["quiz_id"] = quiz.get("quiz_id")
    record["benchmark_id"] = quiz.get("benchmark_id")
    record["ollama_load_ms"] = timings.get("model_load_ms")
    record["generated_by"] = quiz.get("generation_model") or plan.get("generation_model")
    record["final_count"] = int(quiz.get("question_count") or len(quiz.get("questions") or []))
    if plan.get("requested_count") is not None:
        record["requested_count"] = int(plan["requested_count"])
    if results:
        record["validated_count"] = int(results.get("accepted") or 0) + int(results.get("accepted_with_warnings") or 0)
        record["rejected_count"] = int(results.get("rejected") or 0)
        record["grounding_rejections"] = int(results.get("grounding_rejections") or 0)
        reasons = dict(results.get("rejection_codes") or {})
        if results.get("response_failures"):
            reasons["response_failure"] = int(results["response_failures"])
        record["rejection_reasons"] = reasons
    record["question_type_distribution"] = plan.get("type_distribution")
    record["prompt_tokens"] = _sum_or_none(call.get("prompt_tokens") for call in calls)
    record["generated_tokens"] = _sum_or_none(call.get("generated_tokens") for call in calls)
    record["tokens_per_second"] = _tokens_per_second(calls)
    record["generation_config"] = {
        "max_llm_calls": plan.get("max_llm_calls"),
        "seed": None,
        "calls": [
            {key: call.get(key) for key in ("call", "temperature", "num_ctx", "num_predict", "keep_alive")}
            for call in calls
        ],
    }
    # Diagnostics are the primary timing source; the quiz's own timings fill any gap.
    for key, source in (("retrieval_ms", "topic_chunk_retrieval_ms"), ("total_ms", "total_ms")):
        if record[key] is None and timings.get(source) is not None:
            record[key] = timings[source]
    if record["llm_calls"] is None and plan.get("llm_calls") is not None:
        record["llm_calls"] = plan["llm_calls"]


def run_once(model: dict, inputs: dict, config: dict, run_number: int, owner_id: str,
             benchmark_id: str, warmup: dict | None = None) -> dict:
    """Generate one measured benchmark quiz (the model is already warm). Never raises: any failure
    is recorded on the run."""
    model_ref = None
    try:
        model_ref = resolve_generation_model(model["model_id"])
    except Exception:  # recorded below, with model_ref left null
        pass
    record = _empty_run(model, model_ref, inputs, config, run_number)
    try:
        if model_ref is None:
            raise BenchmarkModelMismatch(f"{model['model_id']} is not an allowed generation model.")
        if warmup is not None and not warmup.get("success"):
            raise BenchmarkWarmupFailed(f"warm-up failed: {(warmup.get('error') or {}).get('message')}")
        _assert_inputs_unchanged(inputs, owner_id, "before")
        with quiz_diagnostics.capture_summaries() as summaries, saving_benchmark_quizzes(benchmark_id):
            try:
                quiz = generate_quiz(
                    document_id=inputs["document_id"],
                    difficulty=config["difficulty"],
                    assessment_scope=BENCHMARK_SCOPE,
                    topic_id=None,
                    regenerate=True,
                    owner_id=owner_id,
                    model_id=model_ref,
                    question_count=config["question_count"],
                    quiz_name=f"[Benchmark] {model['label']} · run {run_number}",
                )
            finally:
                _apply_summary(record, summaries[-1] if summaries else {})
        _apply_quiz(record, quiz)
        if record["cache_hit"]:
            raise BenchmarkCacheHit("run was served from the quiz cache.")
        generated_by = (record["generated_by"] or {}).get("model_id")
        if generated_by != model["model_id"]:
            raise BenchmarkModelMismatch(f"quiz was generated by {generated_by!r}, not {model['model_id']!r}.")
        if record["quiz_id"] and record["benchmark_id"] != benchmark_id:
            raise RuntimeError("benchmark quiz was not marked as benchmark output.")
        _assert_inputs_unchanged(inputs, owner_id, "during")
        record["success"] = True
    except Exception as error:
        record["success"] = False
        record["error"] = {"type": type(error).__name__, "message": str(error)[:500]}
    record["finished_at"] = _now()
    return record


# ---------------------------------------------------------------------------
# Aggregates
# ---------------------------------------------------------------------------

def _percentile(values: list[float], fraction: float) -> float | None:
    """Linear-interpolated percentile of `values` (None when empty)."""
    if not values:
        return None
    ordered = sorted(values)
    position = (len(ordered) - 1) * fraction
    lower, upper = math.floor(position), math.ceil(position)
    return ordered[lower] + (ordered[upper] - ordered[lower]) * (position - lower)


def _mean(values: list[float]) -> float | None:
    return sum(values) / len(values) if values else None


def _round(value, digits=3):
    return round(value, digits) if isinstance(value, (int, float)) else None


def aggregate_runs(runs: list[dict], warmups: list[dict] | None = None) -> list[dict]:
    """Per-model aggregates. Rates over all runs (a failed run counts as 0 final questions);
    latency/throughput over successful measured runs only (warm-up/cold start is never included and
    is reported separately). No combined or "winner" score."""
    warmup_by_model = {warmup.get("model_id"): warmup for warmup in warmups or []}
    rows = []
    for model in BENCHMARK_MODELS:
        model_runs = [run for run in runs if run.get("model_id") == model["model_id"]]
        warmup = warmup_by_model.get(model["model_id"]) or {}
        if not model_runs:
            continue
        ok = [run for run in model_runs if run.get("success")]
        requested = sum(int(run.get("requested_count") or 0) for run in model_runs)
        final = sum(int(run.get("final_count") or 0) for run in ok)
        validated = sum(int(run.get("validated_count") or 0) for run in ok if run.get("validated_count") is not None)
        grounding_rejected = sum(
            int(run.get("grounding_rejections") or 0) for run in ok if run.get("grounding_rejections") is not None
        )
        latencies = [run["total_ms"] / 1000 for run in ok if isinstance(run.get("total_ms"), (int, float))]
        ok_minutes = sum(run["total_ms"] for run in ok if isinstance(run.get("total_ms"), (int, float))) / 60000
        retries = [run["retries"] for run in model_runs if isinstance(run.get("retries"), (int, float))]
        rates = [run["tokens_per_second"] for run in ok if isinstance(run.get("tokens_per_second"), (int, float))]
        rows.append({
            "model_id": model["model_id"],
            "runs": len(model_runs),
            "failures": len(model_runs) - len(ok),
            "success_rate": _round(len(ok) / len(model_runs)),
            "final_question_rate": _round(final / requested) if requested else None,
            "grounding_rate": _round(validated / (validated + grounding_rejected)) if validated + grounding_rejected else None,
            "avg_latency_seconds": _round(_mean(latencies), 2),
            "p50_latency_seconds": _round(_percentile(latencies, 0.5), 2),
            "p95_latency_seconds": _round(_percentile(latencies, 0.95), 2),
            "avg_retries": _round(_mean(retries), 2),
            "avg_tokens_per_second": _round(_mean(rates), 1),
            "questions_per_minute": _round(final / ok_minutes, 2) if ok_minutes else None,
            "model_prepare_ms": warmup.get("model_prepare_ms"),
            "warm_ms": warmup.get("warm_ms"),
            "cold_start_ms": warmup.get("cold_start_ms"),
        })
    return rows


