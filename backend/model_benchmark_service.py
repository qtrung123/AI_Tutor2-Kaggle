# Orchestration
# ---------------------------------------------------------------------------

def prepare_benchmark(owner_id: str, document_ids: list[str], difficulty: str, question_count: int,
                      runs: int = DEFAULT_RUNS) -> dict:
    """Validate the request, snapshot every input once and store the initial "running" state."""
    document_ids = list(dict.fromkeys(str(doc_id).strip() for doc_id in document_ids or [] if str(doc_id).strip()))
    if not document_ids:
        raise ValueError("Choose at least one document.")
    if len(document_ids) > MAX_DOCUMENTS:
        raise ValueError(f"Choose at most {MAX_DOCUMENTS} documents.")
    if difficulty not in QUIZ_DIFFICULTIES:
        raise ValueError("difficulty must be easy, medium, or difficult.")
    if question_count not in QUIZ_V2_ALLOWED_QUESTION_COUNTS:
        raise ValueError(f"question_count must be one of {sorted(QUIZ_V2_ALLOWED_QUESTION_COUNTS)}.")
    if not isinstance(runs, int) or not 1 <= runs <= MAX_RUNS:
        raise ValueError(f"runs must be between 1 and {MAX_RUNS}.")
    known = _document_lookup(owner_id)
    missing = [doc_id for doc_id in document_ids if doc_id not in known]
    if missing:
        raise ValueError(f"Unknown document(s): {', '.join(missing)}")
    # No silent fallback: both models must resolve before anything runs.
    models = []
    for model in BENCHMARK_MODELS:
        model_ref = resolve_generation_model(model["model_id"])
        described = describe_generation_model(model_ref)
        models.append({**model, "model_ref": model_ref, "quantization": described.get("quantization")})

    state = {
        "benchmark_id": str(uuid4()),
        "status": "running",
        "started_at": _now(),
        "finished_at": None,
        "generated_at": None,
        "config": {
            "models": models,
            "documents": [_document_inputs(doc_id, owner_id) for doc_id in document_ids],
            "difficulty": difficulty,
            "question_count": question_count,
            "runs_per_model_per_document": runs,
            "assessment_scope": BENCHMARK_SCOPE,
            "quiz_engine_version": QUIZ_ENGINE_VERSION,
            "quiz_prompt_version": QUIZ_PROMPT_VERSION,
            "order": "sequential: model (warm-up, then measured runs) -> document -> run",
            "latency_scope": "generate_quiz pipeline total_ms; warm-up/cold start excluded",
        },
        "progress": {"completed": 0, "total": len(models) * len(document_ids) * runs},
        "warmups": [],
        "runs": [],
        "results": [],
    }
    save_benchmark_state(state)
    return state


def execute_benchmark(state: dict, owner_id: str) -> dict:
    """Run every (model, document, run) sequentially; record failures and keep going."""
    config = state["config"]
    try:
        for model in config["models"]:
            warmup = warm_up_model(model)
            state["warmups"].append(warmup)
            save_benchmark_state(state)
            for inputs in config["documents"]:
                for run_number in range(1, config["runs_per_model_per_document"] + 1):
                    state["runs"].append(run_once(
                        model, inputs, config, run_number, owner_id, state["benchmark_id"], warmup,
                    ))
                    state["progress"]["completed"] = len(state["runs"])
                    state["results"] = aggregate_runs(state["runs"], state["warmups"])
                    save_benchmark_state(state)
        state["status"] = "completed"
    except Exception as error:  # an orchestration bug, not a run failure: keep what was measured
        state["status"] = "failed"
        state["error"] = {"type": type(error).__name__, "message": str(error)[:500]}
    state["finished_at"] = state["generated_at"] = _now()
    state["results"] = aggregate_runs(state["runs"], state["warmups"])
    save_benchmark_state(state)
    return state


def run_benchmark(owner_id: str, document_ids: list[str], difficulty: str, question_count: int,
                  runs: int = DEFAULT_RUNS) -> dict:
    """Synchronous benchmark (validate, snapshot, run everything)."""
    return execute_benchmark(prepare_benchmark(owner_id, document_ids, difficulty, question_count, runs), owner_id)


_lock = threading.Lock()
_active_thread: threading.Thread | None = None


def is_benchmark_running() -> bool:
    return bool(_active_thread and _active_thread.is_alive())


def start_benchmark(owner_id: str, document_ids: list[str], difficulty: str, question_count: int,
                    runs: int = DEFAULT_RUNS) -> dict:
    """Validate and start one background benchmark; only one can run at a time."""
    global _active_thread
    with _lock:
        if is_benchmark_running():
            raise BenchmarkAlreadyRunning("A benchmark is already running.")
        state = prepare_benchmark(owner_id, document_ids, difficulty, question_count, runs)
        _active_thread = threading.Thread(
            target=execute_benchmark, args=(state, owner_id), name="quiz-model-benchmark", daemon=True,
        )
        _active_thread.start()
    return state


def current_benchmark_state() -> dict:
    """Stored state; a "running" benchmark whose worker is gone (server restart) reads as interrupted."""
    state = load_benchmark_state()
    if state.get("status") == "running" and not is_benchmark_running():
        state["status"] = "interrupted"
    return state
