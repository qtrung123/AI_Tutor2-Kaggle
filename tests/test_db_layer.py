def without_database_url():
    environment = {key: value for key, value in os.environ.items() if key != "DATABASE_URL"}
    return patch.dict(os.environ, environment, clear=True)


class BackendSelectionTests(unittest.TestCase):
    def test_no_database_url_selects_sqlite(self):
        with without_database_url():
            self.assertEqual(db.selected_backend(), db.SQLITE)

    def test_blank_database_url_selects_sqlite(self):
        with patch.dict(os.environ, {"DATABASE_URL": "   "}):
            self.assertEqual(db.selected_backend(), db.SQLITE)

    def test_postgres_urls_select_postgres(self):
        for url in (SECRET_URL, "postgres://u:p@h/d", "POSTGRESQL://u:p@h/d"):
            with self.subTest(url=url.split("://")[0]), patch.dict(os.environ, {"DATABASE_URL": url}):
                self.assertEqual(db.selected_backend(), db.POSTGRES)

    def test_sqlite_demo_mode_ignores_database_url(self):
        with patch.dict(os.environ, {"DATABASE_URL": SECRET_URL, "AI_TUTOR_ALLOW_SQLITE": "1"}):
            self.assertEqual(db.selected_backend(), db.SQLITE)
            self.assertEqual(db.database_url(), "")

    def test_unsupported_url_is_rejected_without_echoing_it(self):
        with patch.dict(os.environ, {"DATABASE_URL": "mysql://alice:s3cr3t-pw@db.private-host.example/tutor"}):
            with self.assertRaises(db.DatabaseConfigurationError) as caught:
                db.selected_backend()
        for part in ("s3cr3t-pw", "alice", "db.private-host.example"):
            self.assertNotIn(part, str(caught.exception))


class SqlRewriteTests(unittest.TestCase):
    def test_question_marks_become_psycopg_placeholders(self):
        self.assertEqual(
            db.to_pyformat("SELECT * FROM users WHERE id = ? AND email = ?"),
            "SELECT * FROM users WHERE id = %s AND email = %s",
        )

    def test_named_parameters_become_psycopg_named_placeholders(self):
        self.assertEqual(
            db.to_pyformat("UPDATE t SET status=:target, at=COALESCE(at, :now) WHERE id=:id AND x='a:b'", named=True),
            "UPDATE t SET status=%(target)s, at=COALESCE(at, %(now)s) WHERE id=%(id)s AND x='a:b'",
        )

    def test_quoted_text_and_comments_are_not_rewritten(self):
        sql = "SELECT 'why?', \"odd?col\" FROM t -- really?\nWHERE a = ? /* b = ? */"
        self.assertEqual(
            db.to_pyformat(sql),
            "SELECT 'why?', \"odd?col\" FROM t -- really?\nWHERE a = %s /* b = ? */",
        )

    def test_doubled_quotes_stay_inside_the_literal(self):
        self.assertEqual(db.to_pyformat("SELECT 'it''s ?' WHERE x = ?"), "SELECT 'it''s ?' WHERE x = %s")

    def test_percent_signs_are_escaped_everywhere(self):
        self.assertEqual(
            db.to_pyformat("SELECT 100 % 7, 'a%b' WHERE name LIKE ?"),
            "SELECT 100 %% 7, 'a%%b' WHERE name LIKE %s",
        )

    def test_unterminated_quote_is_rejected(self):
        with self.assertRaises(ValueError):
            db.to_pyformat("SELECT 'oops WHERE a = ?")

    def test_ddl_maps_sqlite_types_outside_literals(self):
        ddl = "CREATE TABLE t (id INTEGER PRIMARY KEY AUTOINCREMENT, score REAL NOT NULL, note TEXT DEFAULT 'REAL')"
        self.assertEqual(
            db.postgres_ddl(ddl),
            "CREATE TABLE t (id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, "
            "score DOUBLE PRECISION NOT NULL, note TEXT DEFAULT 'REAL')",
        )

    def test_ddl_refuses_collate_nocase(self):
        with self.assertRaises(ValueError):
            db.postgres_ddl("CREATE TABLE t (email TEXT COLLATE NOCASE UNIQUE)")


class RowTests(unittest.TestCase):
    def test_row_matches_sqlite_row_access(self):
        row = db.Row(["id", "Title", "id"], [1, "Hello", 2])
        self.assertEqual(row[0], 1)
        self.assertEqual(row["title"], "Hello")
        self.assertEqual(row["ID"], 1)  # first duplicate wins, like sqlite3.Row
        self.assertEqual(row.keys(), ["id", "Title", "id"])
        self.assertEqual(dict(db.Row(["a", "b"], [1, 2])), {"a": 1, "b": 2})
        self.assertEqual(list(row), [1, "Hello", 2])
        with self.assertRaises(IndexError):
            row["missing"]


class SQLiteConnectionTests(unittest.TestCase):
    def setUp(self):
        self.temp_dir = tempfile.TemporaryDirectory()
        self.path = Path(self.temp_dir.name) / "nested" / "app.db"
        self.env = without_database_url()
        self.env.start()
        with db.connect(self.path) as connection:
            connection.executescript(
                "CREATE TABLE parent (id TEXT PRIMARY KEY);"
                "CREATE TABLE child (id TEXT PRIMARY KEY, parent_id TEXT NOT NULL REFERENCES parent(id));"
            )

    def tearDown(self):
        self.env.stop()
        self.temp_dir.cleanup()

    def rows(self, table):
        raw = sqlite3.connect(self.path)
        try:
            return [row[0] for row in raw.execute(f"SELECT id FROM {table}")]
        finally:
            raw.close()

    def test_commits_on_success_and_returns_named_rows(self):
        with db.connect(self.path) as connection:
            self.assertEqual(connection.backend, db.SQLITE)
            connection.execute("INSERT INTO parent (id) VALUES (?)", ("p1",))
            self.assertEqual(connection.execute("SELECT id FROM parent").fetchone()["id"], "p1")
        self.assertEqual(self.rows("parent"), ["p1"])

    def test_rolls_back_and_closes_on_failure(self):
        with self.assertRaises(RuntimeError):
            with db.connect(self.path) as connection:
                connection.execute("INSERT INTO parent (id) VALUES (?)", ("p1",))
                raise RuntimeError("boom")
        self.assertEqual(self.rows("parent"), [])
        with self.assertRaises(sqlite3.ProgrammingError):
            connection.execute("SELECT 1")

    def test_explicit_transaction_api_matches_sqlite3(self):
        connection = db.connect(self.path)
        try:
            connection.begin_immediate()
            connection.execute("INSERT INTO parent (id) VALUES (?)", ("p1",))
            connection.rollback()
            connection.begin_immediate()
            connection.executemany("INSERT INTO parent (id) VALUES (?)", [("p2",), ("p3",)])
            connection.commit()
        finally:
            connection.close()
        self.assertEqual(sorted(self.rows("parent")), ["p2", "p3"])

    def test_constraint_violations_raise_the_shared_integrity_error(self):
        with self.assertRaises(db.IntegrityError):
            with db.connect(self.path) as connection:
                connection.execute("INSERT INTO child (id, parent_id) VALUES (?, ?)", ("c1", "missing"))
        self.assertEqual(self.rows("child"), [])

    def test_add_column_is_idempotent(self):
        with db.connect(self.path) as connection:
            self.assertTrue(db.add_column(connection, "parent", "label", "TEXT NOT NULL DEFAULT 'x'"))
            self.assertFalse(db.add_column(connection, "parent", "label", "TEXT NOT NULL DEFAULT 'x'"))
            self.assertEqual(db.table_columns(connection, "parent"), {"id", "label"})

    def test_sqlite_schema_initializers_run_on_every_call(self):
        calls = []
        for _ in range(2):
            db.ensure_schema("probe", self.path, lambda connection: calls.append(connection.backend))
        self.assertEqual(calls, [db.SQLITE, db.SQLITE])


class PostgresConnectionTests(unittest.TestCase):
    def setUp(self):
        self.temp_dir = tempfile.TemporaryDirectory()
        self.backing = Path(self.temp_dir.name) / "postgres.db"
        self.announced = patch.object(db, "_announced", set())
        self.announced.start()

    def tearDown(self):
        self.announced.stop()
        self.temp_dir.cleanup()

    def test_pooled_connections_adapt_sql_rows_and_bools(self):
        fake = FakePsycopg(self.backing)
        output = io.StringIO()
        with fake.installed(SECRET_URL), redirect_stdout(output):
            for index in range(2):
                with db.connect("unused.db") as connection:
                    self.assertEqual(connection.backend, db.POSTGRES)
                    connection.executescript("CREATE TABLE IF NOT EXISTS t (id TEXT PRIMARY KEY, label TEXT, flag INTEGER, score REAL);")
                    connection.execute("INSERT INTO t (id, label, flag, score) VALUES (?, ?, ?, ?)", (f"r{index}", "50% ?", True, 0.5))
            with db.connect("unused.db") as connection:
                connection.execute("UPDATE t SET flag = :flag WHERE id = :id", {"flag": False, "id": "r0"})
                rows = connection.execute("SELECT id, flag, label FROM t ORDER BY id").fetchall()
        self.assertEqual(output.getvalue(), "[db] backend=postgres connected\n")
        self.assertEqual([(row["id"], row[1], row["LABEL"]) for row in rows], [("r0", 0, "50% ?"), ("r1", 1, "50% ?")])
        self.assertIsInstance(rows[0], db.Row)
        self.assertEqual(len(fake.pools), 1)
        options = fake.pools[0].options
        self.assertIsNotNone(options["check"])
        self.assertEqual(fake.pools[0].kwargs["prepare_threshold"], None)
        self.assertEqual(fake.pools[0].kwargs["connect_timeout"], 10)
        self.assertIn("INSERT INTO t (id, label, flag, score) VALUES (%s, %s, %s, %s)", fake.statements)
        self.assertIn("UPDATE t SET flag = %(flag)s WHERE id = %(id)s", fake.statements)
        self.assertTrue(any("score DOUBLE PRECISION" in statement for statement in fake.statements))

    def test_rolls_back_postgres_work_on_failure(self):
        fake = FakePsycopg(self.backing)
        with fake.installed(SECRET_URL), redirect_stdout(io.StringIO()):
            with db.connect("unused.db") as connection:
                connection.executescript("CREATE TABLE IF NOT EXISTS t (id TEXT PRIMARY KEY);")
            with self.assertRaises(db.IntegrityError):
                with db.connect("unused.db") as connection:
                    connection.execute("INSERT INTO t (id) VALUES (?)", ("a",))
                    connection.execute("INSERT INTO t (id) VALUES (?)", ("a",))
        raw = sqlite3.connect(self.backing)
        try:
            self.assertEqual(raw.execute("SELECT COUNT(*) FROM t").fetchone()[0], 0)
        finally:
            raw.close()

    def test_postgres_schema_initializer_runs_once_per_process_under_a_lock(self):
        fake = FakePsycopg(self.backing)
        calls = []
        with fake.installed(SECRET_URL), redirect_stdout(io.StringIO()):
            for _ in range(3):
                db.ensure_schema("probe", "unused.db", lambda connection: calls.append(connection.backend))
        self.assertEqual(calls, [db.POSTGRES])
        self.assertEqual(sum("pg_advisory_xact_lock" in statement for statement in fake.statements), 1)

    def test_postgres_add_column_uses_if_not_exists(self):
        fake = FakePsycopg(self.backing)
        with fake.installed(SECRET_URL), redirect_stdout(io.StringIO()):
            with db.connect("unused.db") as connection:
                connection.executescript("CREATE TABLE t (id TEXT PRIMARY KEY);")
                with patch.object(db, "table_columns", return_value={"id"}):
                    self.assertTrue(db.add_column(connection, "t", "score", "REAL NOT NULL DEFAULT 0"))
        self.assertIn("ALTER TABLE t ADD COLUMN IF NOT EXISTS score DOUBLE PRECISION NOT NULL DEFAULT 0", fake.statements)

    def test_connection_failure_never_exposes_credentials(self):
        libpq_message = (
            'connection to server at "db.private-host.example" (10.0.0.5), port 5432 failed: '
            'FATAL: password authentication failed for user "alice"'
        )
        fake = FakePsycopg(self.backing, connect_error=OperationalError(libpq_message))
        output = io.StringIO()
        with fake.installed(SECRET_URL), redirect_stdout(output):
            with self.assertRaises(db.DatabaseConnectionError) as caught:
                db.connect("unused.db")
        rendered = "".join(traceback.format_exception(caught.exception)) + output.getvalue()
        self.assertIn("backend=postgres connection failed (PoolTimeout; authentication failed: check the user and password)", rendered)
        for part in SECRET_PARTS:
            self.assertNotIn(part, rendered)

    def test_connection_failure_reports_only_the_sqlstate(self):
        error = OperationalError('FATAL: password authentication failed for user "alice"')
        error.sqlstate = "28P01"
        fake = FakePsycopg(self.backing, connect_error=error)
        with fake.installed(SECRET_URL), redirect_stdout(io.StringIO()):
            with self.assertRaises(db.DatabaseConnectionError) as caught:
                db.connect("unused.db")
        self.assertEqual(
            str(caught.exception),
            "[db] backend=postgres connection failed "
            "(PoolTimeout; sqlstate=28P01: authentication failed: check the user and password)",
        )

    def test_missing_driver_is_reported_without_the_url(self):
        with patch.dict(sys.modules, {"psycopg": None, "psycopg_pool": None}), \
                patch.dict(os.environ, {"DATABASE_URL": SECRET_URL}), patch.object(db, "_pools", {}):
            with self.assertRaises(db.DatabaseConfigurationError) as caught:
                db.connect("unused.db")
        self.assertIn("not installed", str(caught.exception))
        for part in SECRET_PARTS:
            self.assertNotIn(part, str(caught.exception))

    def test_sqlite_selection_is_announced_once_and_forced_sqlite_is_silent(self):
        output = io.StringIO()
        with without_database_url(), redirect_stdout(output):
            path = Path(self.temp_dir.name) / "local.db"
            with db.connect(path, backend=db.SQLITE):
                pass
            self.assertEqual(output.getvalue(), "")
            for _ in range(2):
                with db.connect(path):
                    pass
        self.assertEqual(output.getvalue(), "[db] backend=sqlite\n")


